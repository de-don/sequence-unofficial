"""Generate docs/api.md from the endpoint registry and the sanitized samples.

usage: python tools/gen_docs.py           (rewrites docs/api.md)
       python tools/gen_docs.py --check   (exit 1 if docs/api.md is out of date)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from sequence_unofficial.client import DEFAULT_BASE_URL
from sequence_unofficial.endpoints import ENDPOINTS, Endpoint

ROOT = Path(__file__).resolve().parent.parent
SAMPLES = ROOT / "docs" / "samples" / "samples.json"
OUT = ROOT / "docs" / "api.md"
MAX_EXAMPLE_LINES = 45

HEADER = f"""# API reference (reverse-engineered)

> Generated by `tools/gen_docs.py` from the endpoint registry (`src/sequence_unofficial/endpoints.py`)
> and the sanitized samples in `docs/samples/`. **Do not edit by hand.**
> Unofficial documentation of the web app's own backend (`{DEFAULT_BASE_URL}`); it may change at any time.

- **verified**: request and response were seen in a capture on the stated date.
- **experimental**: only partly observed (see the note); a warning is logged when the endpoint is called.
- All requests send `Accept: application/json`. Login: `POST /signin` with `{{"email", "password"}}` returns
  `{{"user": {{...}}, "csrf": "..."}}` and sets a session cookie.
- **Unverified:** the header that must carry the CSRF token on writes (the client defaults to `X-CSRF-Token`,
  configurable). **No write endpoint has been captured yet**, so none is implemented.
- Numbers often arrive as strings (`"5.0"`); durations are milliseconds. Planner dates are local dates.
"""


def _example(sample: dict[str, Any] | None, key: str) -> list[str]:
    if sample is None:
        return ["_No sample available._"]
    lines: list[str] = []
    if sample.get("query"):
        lines.append(f"Query seen: `{sample['query']}`\n")
    if sample.get("request") is not None:
        lines += ["Request body:", "```json", json.dumps(sample["request"], indent=1), "```", ""]
    if sample["response"] is None:
        return [*lines, "_Response body was not captured (truncated in the capture)._"]
    text = json.dumps(sample["response"], indent=1, ensure_ascii=False).splitlines()
    if len(text) > MAX_EXAMPLE_LINES:
        text = [*text[:MAX_EXAMPLE_LINES], f"... ({len(text) - MAX_EXAMPLE_LINES} more lines)"]
    return [*lines, "Response (sanitized):", "```json", *text, "```"]


def _returns(ep: Endpoint[Any]) -> str:
    name = ep.model.__name__ if ep.model else "?"
    return {"one": name, "list": f"list[{name}]"}.get(ep.returns, "plain JSON")


def _section(ep: Endpoint[Any], samples: dict[str, dict[str, Any]]) -> list[str]:
    status = f"**{ep.status}**"
    if ep.status == "verified" and ep.verified_on:
        status += f" (verified on {ep.verified_on})"
    out = [
        f"## `{ep.method} {ep.path}`",
        "",
        f"- Client: `Sequence.{ep.resource}` (registry name `{ep.name}`)",
        f"- Status: {status}",
        f"- Returns: {_returns(ep)}",
    ]
    if ep.query:
        out.append("- Query parameters seen: " + ", ".join(f"`{q}`" for q in ep.query))
    if ep.note:
        out.append(f"- Note: {ep.note}")
    return [*out, "", *_example(samples.get(ep.sample_key), ep.sample_key), ""]


def render() -> str:
    raw = json.loads(SAMPLES.read_text(encoding="utf-8"))
    samples = {f"{s['method']} {s['path']}": s for s in raw}
    parts = [
        HEADER,
        "## Write endpoints",
        "",
        "None captured yet. See the roadmap in `docs/decisions.md`.",
        "",
    ]
    for ep in sorted(ENDPOINTS, key=lambda e: (e.resource, e.path)):
        parts += _section(ep, samples)
    return "\n".join(parts).rstrip() + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/api.md is out of date: run `python tools/gen_docs.py`")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
